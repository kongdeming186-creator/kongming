#!/bin/bash
# 城运街道综合管理平台 - 远程访问服务
# 等价于 Windows 的 远程访问.bat

set -e

echo "========================================"
echo "   城运街道综合管理平台"
echo "   远程访问模式"
echo "========================================"
echo ""
echo "[提示] 启动后，其他电脑可以通过以下地址访问："
echo ""
echo "   http://本机IP地址:5173/"
echo ""
echo "[提示] 查看本机IP地址："
echo "   运行 hostname -I 命令"
echo ""

# 检查是否已打包
echo "正在检查是否已打包..."
if [ ! -d "dist" ]; then
    echo "[1/2] 正在打包项目（首次需要几分钟）..."
    npm run build
    echo ""
fi

echo "[2/2] 正在启动远程访问服务..."
echo ""
echo "========================================"
echo "   按 Ctrl+C 可停止服务"
echo "========================================"
echo ""

npx serve dist -l 5173
